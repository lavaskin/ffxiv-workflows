#:package Microsoft.CodeAnalysis.CSharp@5.0.0

using System.Diagnostics;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

const string SettingsFile = ".github/check-comments.json";
const string UpdateCommand = "dotnet run --file ../ffxiv-workflows/check-comments/check-comments.cs -- update";

string mode = args.ElementAtOrDefault(0) ?? "check";
if (mode is not ("check" or "update" or "list"))
{
	Console.Error.WriteLine("Usage: check-comments.cs [check | update | list [path prefix]]");
	return 2;
}

string root = RepoRoot();
string settingsPath = Path.Combine(root, SettingsFile);
var settings = File.Exists(settingsPath) ? JsonNode.Parse(File.ReadAllText(settingsPath))!.AsObject() : [];
string[] skipped = settings["skip"]?.AsArray().Select(s => s!.GetValue<string>()).ToArray() ?? [];
var baseline = settings["baseline"]?.AsObject().ToDictionary(entry => entry.Key, entry => entry.Value!.GetValue<int>()) ?? [];

var comments = RepoFiles(root)
	.Where(file => !skipped.Any(file.StartsWith))
	.SelectMany(file => CommentScanner.Scan(file, File.ReadAllText(Path.Combine(root, file))))
	.ToList();
var counts = comments.GroupBy(c => c.File).ToDictionary(g => g.Key, g => g.Count());

if (mode == "list")
{
	string prefix = args.ElementAtOrDefault(1) ?? "";
	foreach (var comment in comments.Where(c => c.File.StartsWith(prefix, StringComparison.Ordinal))) Console.WriteLine(comment);
	return 0;
}

if (mode == "update")
{
	baseline = baseline
		.Select(entry => (entry.Key, Count: Math.Min(entry.Value, counts.GetValueOrDefault(entry.Key))))
		.Where(entry => entry.Count > 0)
		.ToDictionary(entry => entry.Key, entry => entry.Count);
	settings["baseline"] = new JsonObject(baseline
		.OrderBy(entry => entry.Key, StringComparer.Ordinal)
		.Select(entry => KeyValuePair.Create(entry.Key, (JsonNode?)entry.Value)));
	settings["skip"] ??= new JsonArray();
	Directory.CreateDirectory(Path.GetDirectoryName(settingsPath)!);
	File.WriteAllText(settingsPath, settings.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");
}

bool annotate = Environment.GetEnvironmentVariable("GITHUB_ACTIONS") == "true";
var over = counts.Where(file => file.Value > baseline.GetValueOrDefault(file.Key)).OrderBy(file => file.Key, StringComparer.Ordinal).ToList();
var under = baseline.Where(file => counts.GetValueOrDefault(file.Key) < file.Value).OrderBy(file => file.Key, StringComparer.Ordinal).ToList();

foreach (var (file, count) in over)
{
	Console.WriteLine($"{file} has {count} comments, over its {baseline.GetValueOrDefault(file)}. Move each into an ADR or a ticket and delete it (the delete-comment skill):");
	foreach (var comment in comments.Where(c => c.File == file))
	{
		Console.WriteLine("  " + comment);
		if (annotate) Console.WriteLine($"::error file={comment.File},line={comment.FirstLine},endLine={comment.LastLine}::A code comment. Move it into an ADR or a ticket and delete it.");
	}
	Console.WriteLine();
}
foreach (var (file, count) in under)
{
	Console.WriteLine($"{file} has {counts.GetValueOrDefault(file)} comments, under its baseline of {count}: lower it with {UpdateCommand}");
}

if (over.Count > 0 || under.Count > 0) return 1;
Console.WriteLine($"{comments.Count} comments, none over or under {SettingsFile}'s baseline.");
return 0;

static string RepoRoot() => Git("rev-parse --show-toplevel", Directory.GetCurrentDirectory()).Trim();

static IEnumerable<string> RepoFiles(string root) =>
	Git("ls-files -z --cached --others --exclude-standard", root)
		.Split('\0', StringSplitOptions.RemoveEmptyEntries)
		.Where(file => File.Exists(Path.Combine(root, file)))
		.Distinct()
		.Order(StringComparer.Ordinal);

static string Git(string arguments, string directory)
{
	using var git = Process.Start(new ProcessStartInfo("git", arguments)
	{
		WorkingDirectory = directory,
		RedirectStandardOutput = true,
	})!;
	string output = git.StandardOutput.ReadToEnd();
	git.WaitForExit();
	if (git.ExitCode != 0) throw new InvalidOperationException($"git {arguments} failed in {directory}");
	return output;
}

sealed record CodeComment(string File, int FirstLine, int LastLine, string Text)
{
	public override string ToString() =>
		$"{File}:{(FirstLine == LastLine ? $"{FirstLine}" : $"{FirstLine}-{LastLine}")}: {Preview}";

	private string Preview
	{
		get
		{
			string flat = Regex.Replace(Text, @"\s+", " ").Trim();
			return flat.Length <= 120 ? flat : flat[..117] + "...";
		}
	}
}

static partial class CommentScanner
{
	public static readonly string[] Allowed =
	[
		"<auto-generated",
		"ReSharper disable",
		"ReSharper restore",
		"language=",
		"shellcheck ",
		"#!",
	];

	public static IEnumerable<CodeComment> Scan(string file, string source)
	{
		var found = Path.GetExtension(file) switch
		{
			".cs" => CSharp(source),
			".csproj" or ".props" or ".targets" => Xml(source),
			".yml" or ".yaml" or ".sh" => Hash(source),
			".json" when file.StartsWith(".vscode/") => Slashes(source),
			_ => [],
		};

		return Merge(found.Where(c => !IsAllowed(c.Text)))
			.Select(c => new CodeComment(file, c.First, c.Last, c.Text));
	}

	private static bool IsAllowed(string text)
	{
		string body = CommentMarker().Replace(text, "");
		return Allowed.Any(a => text.StartsWith(a, StringComparison.Ordinal) || body.StartsWith(a, StringComparison.Ordinal));
	}

	private static IEnumerable<(int First, int Last, string Text)> CSharp(string source)
	{
		var tree = CSharpSyntaxTree.ParseText(source);
		return tree.GetRoot().DescendantTrivia()
			.Where(t => t.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia
				or SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia)
			.Select(t =>
			{
				string text = t.ToFullString().TrimEnd();
				int first = tree.GetLineSpan(t.Span).StartLinePosition.Line + 1;
				return (first, first + text.Count(ch => ch == '\n'), text);
			});
	}

	private static IEnumerable<(int First, int Last, string Text)> Xml(string source) =>
		XmlComment().Matches(source).Select(m =>
		{
			int first = LineOf(source, m.Index);
			return (first, first + m.Value.Count(ch => ch == '\n'), m.Value);
		});

	private static IEnumerable<(int First, int Last, string Text)> Hash(string source) =>
		LineComments(source, (line, i) => line[i] == '#' && (i == 0 || char.IsWhiteSpace(line[i - 1])));

	private static IEnumerable<(int First, int Last, string Text)> Slashes(string source) =>
		LineComments(source, (line, i) => line[i] == '/' && i + 1 < line.Length && line[i + 1] == '/');

	private static IEnumerable<(int First, int Last, string Text)> LineComments(string source, Func<string, int, bool> startsComment)
	{
		string[] lines = source.Split('\n');
		for (int n = 0; n < lines.Length; n++)
		{
			string line = lines[n];
			char? quote = null;
			for (int i = 0; i < line.Length; i++)
			{
				char ch = line[i];
				if (quote is not null)
				{
					if (ch == '\\' && quote == '"') i++;
					else if (ch == quote) quote = null;
				}
				else if (ch is '"' or '\'' && (i == 0 || !char.IsLetterOrDigit(line[i - 1])))
				{
					quote = ch;
				}
				else if (startsComment(line, i))
				{
					yield return (n + 1, n + 1, line[i..].TrimEnd());
					break;
				}
			}
		}
	}

	private static IEnumerable<(int First, int Last, string Text)> Merge(IEnumerable<(int First, int Last, string Text)> comments)
	{
		(int First, int Last, string Text)? open = null;
		foreach (var c in comments.OrderBy(c => c.First))
		{
			if (open is { } o && c.First <= o.Last + 1)
			{
				open = (o.First, Math.Max(o.Last, c.Last), o.Text + "\n" + c.Text);
				continue;
			}
			if (open is { } done) yield return done;
			open = c;
		}
		if (open is { } last) yield return last;
	}

	private static int LineOf(string source, int index) => source.AsSpan(0, index).Count('\n') + 1;

	[GeneratedRegex(@"<!--[\s\S]*?-->")]
	private static partial Regex XmlComment();

	[GeneratedRegex(@"^(//+|/\*+|#|<!--)\s*")]
	private static partial Regex CommentMarker();
}
