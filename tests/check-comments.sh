#!/usr/bin/env bash
set -uo pipefail

app=$(cd "$(dirname "$0")/../check-comments" && pwd)/check-comments.cs
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
failures=0

pass() { echo "ok   $1"; }
fail() { echo "FAIL $1"; failures=$((failures + 1)); }

check_comments() { (cd "$work/repo" && dotnet run --file "$app" -- "$@"); }

expect_output() {
	local name=$1 expected=$2
	shift 2
	local actual status
	actual=$(check_comments "$@" 2>&1)
	status=$?
	if ((status)); then
		fail "$name: exited $status:"$'\n'"$actual"
	elif [[ $actual != "$expected" ]]; then
		fail "$name: expected"$'\n'"$expected"$'\n'"got"$'\n'"$actual"
	else
		pass "$name"
	fi
}

expect_failure() {
	local name=$1
	shift
	local actual
	if actual=$(check_comments check 2>&1); then
		fail "$name: passed:"$'\n'"$actual"
		return
	fi
	for message in "$@"; do
		if ! grep -qF -- "$message" <<<"$actual"; then
			fail "$name: expected \"$message\" in:"$'\n'"$actual"
			return
		fi
	done
	pass "$name"
}

expect_baseline() {
	local name=$1 expected=$2 actual
	actual=$(jq -c .baseline "$work/repo/.github/check-comments.json")
	if [[ $actual == "$expected" ]]; then pass "$name"; else fail "$name: expected $expected, got $actual"; fi
}

baseline() {
	mkdir -p "$work/repo/.github"
	printf '{ "skip": ["generated/"], "baseline": %s }\n' "$1" >"$work/repo/.github/check-comments.json"
}

git init -q "$work/repo"
mkdir -p "$work/repo/.vscode" "$work/repo/generated" "$work/repo/src"

cat >"$work/repo/src/a.cs" <<'EOF'
// one
// still one
class A
{
	/// <summary>two</summary>
	string a = "https://example.com";
	string b = @"// not a comment";
	string c = """ /* nor this */ """;
	int d = 1; /* three */
}
// <auto-generated />
// ReSharper disable once UnusedMember.Global
EOF

cat >"$work/repo/ci.yml" <<'EOF'
# one
on: push
name: "#not" # two
run: echo ${#list[@]} it's '#' fine
EOF

cat >"$work/repo/run.sh" <<'EOF'
#!/usr/bin/env bash
# shellcheck disable=SC2016
echo $((10#$n)) '# not' "# nor" # one
EOF

cat >"$work/repo/a.csproj" <<'EOF'
<Project>
  <!-- one
    still one -->
  <PropertyGroup Label="no comment" />
</Project>
EOF

cat >"$work/repo/.vscode/settings.json" <<'EOF'
{
  // one
  "url": "https://example.com"
}
EOF

cat >"$work/repo/generated/skipped.cs" <<'EOF'
// skipped
EOF

cat >"$work/repo/.gitignore" <<'EOF'
ignored.cs
EOF
echo "// ignored" >"$work/repo/ignored.cs"

baseline '{}'

expect_output "list: comments, but not lookalikes, directives, skipped folders or ignored files" "$(
	cat <<'EOF'
.vscode/settings.json:2: // one
a.csproj:2-3: <!-- one still one -->
ci.yml:1: # one
ci.yml:3: # two
run.sh:3: # one
src/a.cs:1-2: // one // still one
src/a.cs:5: /// <summary>two</summary>
src/a.cs:9: /* three */
EOF
)" list

expect_output "list: a path prefix" "src/a.cs:1-2: // one // still one
src/a.cs:5: /// <summary>two</summary>
src/a.cs:9: /* three */" list src/

baseline '{ ".vscode/settings.json": 1, "a.csproj": 1, "ci.yml": 2, "run.sh": 1, "src/a.cs": 3 }'
expect_output "check: every file at its baseline" "8 comments, none over or under .github/check-comments.json's baseline." check

echo "// four" >>"$work/repo/src/a.cs"
expect_failure "check: a file over its baseline" \
	"src/a.cs has 4 comments, over its 3." "src/a.cs:13: // four"

baseline '{ ".vscode/settings.json": 1, "a.csproj": 1, "ci.yml": 2, "run.sh": 1, "src/a.cs": 4 }'
echo "// new" >"$work/repo/src/b.cs"
expect_failure "check: a new file with a comment" \
	"src/b.cs has 1 comments, over its 0." "src/b.cs:1: // new"
rm "$work/repo/src/b.cs"

sed -i '/^# one$/d' "$work/repo/ci.yml"
expect_failure "check: a file under its baseline" \
	"ci.yml has 1 comments, under its baseline of 2: lower it with"

git -C "$work/repo" add -A
git -C "$work/repo" mv run.sh moved.sh
expect_failure "check: a moved file starts at none" \
	"moved.sh has 1 comments, over its 0." "run.sh has 0 comments, under its baseline of 1"
git -C "$work/repo" mv moved.sh run.sh

sed -i '/# one$/d' "$work/repo/run.sh"
baseline '{ ".vscode/settings.json": 1, "a.csproj": 1, "ci.yml": 2, "run.sh": 1, "src/a.cs": 2 }'
check_comments update >/dev/null 2>&1
expect_baseline "update: lowers counts, drops files at none, and never raises one" \
	'{".vscode/settings.json":1,"a.csproj":1,"ci.yml":1,"src/a.cs":2}'
if jq -e '.skip == ["generated/"]' "$work/repo/.github/check-comments.json" >/dev/null; then
	pass "update: keeps the skipped folders"
else
	fail "update: keeps the skipped folders: $(cat "$work/repo/.github/check-comments.json")"
fi
expect_failure "update: a file still over its baseline fails" "src/a.cs has 4 comments, over its 2."

rm "$work/repo/.github/check-comments.json"
expect_failure "check: no settings file means no comments allowed" "src/a.cs has 4 comments, over its 0."

if ((failures)); then
	echo "$failures failed"
	exit 1
fi
